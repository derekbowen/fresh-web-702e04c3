#!/usr/bin/env python3
"""Generate the cleaner SQL from one template.

    python3 -I cleaner/build.py

Reads   cleaner/core.sql.tmpl, text-defects/text_defect_rules.py (every regex), cleaner/reference.py (the
        addendum minimum lengths), duplicate-mapping.csv (2026-11-15; only used to HOLD R6 deletions).
Writes  cleaner/core.sql        the rendered plan (a WITH-list ending in the relation `plan`)
        dry-run.sql             read-only report + approved-manifest.csv
        apply.sql               one transaction: backup, guarded UPDATEs, change log
        rollback.sql            restores a run where the value still has the logged new md5
The core text is pasted byte-identical into dry-run.sql and apply.sql; its md5 is printed in both
headers, and the local test checks it. Opens no network or database connection.
"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import reference as R  # noqa: E402

T = R.T
BEGIN, END = "-- >>> CORE BEGIN", "-- <<< CORE END"


def pg(s):
    return "'" + s.replace("'", "''") + "'"


def render_core():
    tm = open(os.path.join(HERE, "core.sql.tmpl"), encoding="utf-8").read()
    lit = {k: pg(v) for k, v in vars(T).items() if isinstance(v, str) and k.isupper()}
    assert T.COUNT.count("{0,3}?") == 1
    for k in range(4):
        lit[f"COUNT_V{k}"] = pg(T.COUNT.replace("{0,3}?", "{%d}" % k))
    lit["MARK"] = pg(T.ABBREV_MARK)
    lit["BEST_FOR_BAD"] = pg(r"[,\[\]{}\"<>\\]")   # text_defect_rules.best_for_reformat
    lit["MIN_PROSE"] = str(R.MIN_PROSE_CHARS)
    lit["MIN_ANSWER"] = str(R.MIN_ANSWER_CHARS)
    lit["A5_BACKREF"] = pg(R.A5_BACKREF)
    nw = sorted(T.NUMBER_WORDS.items(), key=lambda kv: kv[1])
    lit["NUMBER_WORDS_VALUES"] = ", ".join(
        (f"({pg(w)}::text, {v}::numeric)" if i == 0 else f"({pg(w)}, {v})") for i, (w, v) in enumerate(nw))
    merges = T._dup_merges(os.path.join(OUT, "duplicate-mapping.csv"))
    rows = []
    for i, (url, n) in enumerate(sorted(merges.items())):
        seg = url.rstrip("/").split("/")
        st, ci = seg[-2], seg[-1]
        rows.append(f"({pg(st)}::text, {pg(ci)}::text, {n}::bigint)" if i == 0 else f"({pg(st)}, {pg(ci)}, {n})")
    lit["DUP_MERGES_VALUES"] = ",\n    ".join(rows) if rows else "(null::text, null::text, 0::bigint)"
    out = tm
    for k in sorted(lit, key=len, reverse=True):
        out = out.replace("{" + k + "}", lit[k])
    leftover = [w for w in ("{SING}", "{COUNT_V", "{MARK}", "{MIN_") if w in out]
    assert not leftover, leftover
    return out.strip() + "\n"


def core_block(core):
    return f"{BEGIN} (md5 of the core text: {hashlib.md5(core.encode()).hexdigest()})\n{core}{END}\n"


