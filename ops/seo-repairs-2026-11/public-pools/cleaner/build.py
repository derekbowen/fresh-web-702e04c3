def main():
    core = render_core()
    md5 = hashlib.md5(core.encode()).hexdigest()
    block = core_block(core)
    with open(os.path.join(HERE, "core.sql"), "w", encoding="utf-8") as f:
        f.write(f"-- GENERATED by cleaner/build.py from core.sql.tmpl (md5 of the core text below: {md5})\n"
                f"-- Usage: with <this text> select ... from plan;\n" + core)
    for name, body, what in (("dry-run.sql", DRY_RUN, "dry run, READ ONLY"), ("apply.sql", APPLY, "apply"),
                             ("rollback.sql", ROLLBACK, "rollback")):
        txt = body.format(header=COMMON_HEADER.format(what=what, md5=md5), core_block=block)
        with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
            f.write(txt)
        print("wrote", os.path.join(OUT, name), len(txt), "bytes")
    print("core md5", md5)


if __name__ == "__main__":
    main()
