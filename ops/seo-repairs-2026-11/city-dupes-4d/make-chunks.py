#!/usr/bin/env python3
"""Writes refresh-1.sql .. refresh-4.sql and noop-1.sql .. noop-4.sql with literal slug boundaries.

The database tool (Supabase execute_sql) does not substitute psql variables, so every statement that
runs on production is a literal file. The four ranges are contiguous by construction: range k ends
exactly where range k+1 starts, the first has no lower bound and the last no upper bound. So the four
ranges together cover every row whatever the boundaries are; the boundaries only decide how the rows
are split (about 980 each, ~15 s each at 15.7 ms per row measured on production).

Boundaries: quartiles of the 3,923 host_acq_city rows that stay published with no redirect_to after
apply.sql, computed read-only on production on 2026-11-19 with the row_number query of
test/run_test.sh (in the database's own collation).

Usage: python3 make-chunks.py            (writes the 8 files next to this script)
       python3 make-chunks.py OUTDIR B1 B2 B3   (tests: other boundaries, other directory)
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BOUNDS = [
    'become-a-swimming-pool-host-encino-ca',
    'become-a-swimming-pool-host-manville-nj',
    'become-a-swimming-pool-host-santa-maria-ca',
]

ELIGIBLE = ("c.template_type = 'host_acq_city' and c.status = 'published' and c.redirect_to is null")


def lit(s):
    assert re.fullmatch(r'[a-z0-9-]+', s), s
    return "'" + s + "'"


def ranges(bounds):
    edges = [None] + list(bounds) + [None]
    for k in range(4):
        lo, hi = edges[k], edges[k + 1]
        cond = []
        if lo is not None:
            cond.append('c.slug >= ' + lit(lo))
        if hi is not None:
            cond.append('c.slug < ' + lit(hi))
        desc = '[%s, %s)' % (lo or 'start', hi or 'end')
        yield k + 1, desc, ' and '.join(cond)


REFRESH = """-- Step 4d, refresh {k} of 4: slug range {desc}. Run after apply.sql commits; order does not matter.
-- Generated by make-chunks.py. Same statement as public.refresh_related_slugs_for_template('host_acq_city'),
-- limited to one slug range. compute_related_city_slugs is STABLE and reads only status, redirect_to,
-- template_type, slug and gsc_impressions, none of which this writes, so the 4 ranges give exactly the
-- result of one full refresh. Ordinary triggers fire: updated_at moves on changed rows (as in the real
-- refresh); tg_host_acq_related_refresh does nothing (status, slug and template do not change).
-- Running it twice is harmless: the second run reports changed = 0.
begin;
set local statement_timeout = '55s';
set local lock_timeout = '5s';
with x as (
  select c.id, public.compute_related_city_slugs(c.slug, c.template_type) as new_slugs
  from public.content_pages c
  where {eligible}
    and {cond}
), u as (
  update public.content_pages cp set related_slugs = x.new_slugs
  from x where cp.id = x.id and cp.related_slugs is distinct from x.new_slugs
  returning cp.id
)
select {k} as range_no, (select count(*) from x) as computed, (select count(*) from u) as changed;
commit;
"""

NOOP = """-- Step 4d, check {k} of 4 (read-only): slug range {desc}. Generated by make-chunks.py.
-- Rows whose stored related_slugs differ from a fresh compute. Expect 0 after refresh-{k}.sql.
begin;
set transaction read only;
set local statement_timeout = '55s';
select {k} as range_no, count(*) as rows_in_range,
       count(*) filter (where c.related_slugs is distinct from
                        public.compute_related_city_slugs(c.slug, c.template_type)) as stale
from public.content_pages c
where {eligible}
  and {cond};
rollback;
"""


def main(argv):
    out, bounds = HERE, BOUNDS
    if len(argv) == 5:
        out, bounds = argv[1], argv[2:5]
    elif len(argv) != 1:
        sys.exit(__doc__)
    assert list(bounds) == sorted(bounds) and len(set(bounds)) == 3, bounds
    for k, desc, cond in ranges(bounds):
        for name, tpl in (('refresh', REFRESH), ('noop', NOOP)):
            with open(os.path.join(out, '%s-%d.sql' % (name, k)), 'w') as f:
                f.write(tpl.format(k=k, desc=desc, cond=cond, eligible=ELIGIBLE))


if __name__ == '__main__':
    main(sys.argv)
