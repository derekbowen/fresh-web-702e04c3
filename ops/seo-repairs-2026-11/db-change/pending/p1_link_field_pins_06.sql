from (
  select f.t, f.rid, f.slug, f.col, f.val, n.form, n.path
  from (
    select $seo$content_pages$seo$::text as t, x.id::text as rid, x.slug, $seo$content$seo$::text as col, x.content as val
    from public.content_pages x where x.content ~* $seo$poolrentalnearme|\]\(\s*<?/|href$seo$ and left(x.id::text, 1) in ('a', 'b')
    union all
    select $seo$content_pages$seo$::text as t, x.id::text as rid, x.slug, $seo$body_markdown$seo$::text as col, x.body_markdown as val
    from public.content_pages x where x.body_markdown ~* $seo$poolrentalnearme|\]\(\s*<?/|href$seo$ and left(x.id::text, 1) in ('a', 'b')
    union all
    select $seo$blog_posts$seo$::text as t, x.id::text as rid, x.slug, $seo$content$seo$::text as col, x.content as val
    from public.blog_posts x where x.content ~* $seo$poolrentalnearme|\]\(\s*<?/|href$seo$ and left(x.id::text, 1) in ('a', 'b')
  ) f
  cross join lateral (
    select distinct
      case when m[1] ~* '^https?://poolrentalnearme\.com' then 'n' else 'w' end as form,
      coalesce(nullif(regexp_replace(split_part(split_part(
